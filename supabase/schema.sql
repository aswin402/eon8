-- Eon8 Blog CMS — Supabase Migration Schema (Ready when switching VITE_CMS_PROVIDER=supabase)
-- Run this in the Supabase SQL Editor when moving from the built-in Node API store to Supabase.

create table if not exists public.blog_categories (
  slug text primary key,
  name text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.blog_posts (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  original_slug text,
  title text not null,
  status text not null default 'published' check (status in ('published', 'draft')),
  featured boolean not null default false,
  category text not null default 'Digital Marketing',
  categories text[] not null default array['Digital Marketing']::text[],
  date_display text not null,
  date_iso date not null default current_date,
  read_time text not null default '5 min read',
  author text not null default 'Eon8 Editorial',
  thumbnail text not null default '',
  excerpt text not null default '',
  blocks jsonb not null default '[]'::jsonb,
  seo jsonb not null default '{}'::jsonb,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_blog_posts_status_date on public.blog_posts (status, is_deleted, date_iso desc);
create index if not exists idx_blog_posts_slug on public.blog_posts (slug);

alter table public.blog_categories enable row level security;
alter table public.blog_posts enable row level security;

-- Public readers can view active categories and published non-deleted posts
create policy "Public read blog_categories"
  on public.blog_categories for select
  using (true);

create policy "Public read published blog_posts"
  on public.blog_posts for select
  using (status = 'published' and is_deleted = false);

-- Authenticated Supabase admins can manage all categories and posts
create policy "Authenticated admins full access blog_categories"
  on public.blog_categories for all
  to authenticated
  using (true)
  with check (true);

create policy "Authenticated admins full access blog_posts"
  on public.blog_posts for all
  to authenticated
  using (true)
  with check (true);

