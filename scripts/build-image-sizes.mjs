// Writes src/lib/media/heroImageSizes.ts: width x height of every hero image used by the
// pages, so the hero can reserve the image's space before it loads (no layout shift).
// Run by `npm run build`; run it by hand after changing a hero image in the page data.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'lib', 'media', 'heroImageSizes.ts');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(tsx?)$/.test(e.name)) out.push(p);
  }
  return out;
}

// Hero images appear as mediaSrc (service pages, JSX) or as hero "image": { "src": ... } (NFT,
// influencer pages).
const PATTERNS = [
  /mediaSrc\s*[:=]\s*["']([^"']+\.(?:webp|png|jpe?g|gif|avif))["']/g,
  /["']?image["']?\s*:\s*\{\s*["']?src["']?\s*:\s*["']([^"']+\.(?:webp|png|jpe?g|gif|avif))["']/g,
];

const found = new Set();
for (const file of walk(path.join(ROOT, 'src', 'pages'))) {
  const text = fs.readFileSync(file, 'utf8');
  for (const re of PATTERNS) for (const m of text.matchAll(re)) if (m[1].startsWith('/')) found.add(m[1]);
}

const sizes = {};
for (const src of [...found].sort()) {
  const file = path.join(ROOT, 'public', decodeURIComponent(src));
  if (!fs.existsSync(file)) continue;
  try {
    const { width, height } = await sharp(file).metadata();
    if (width && height) sizes[src] = [width, height];
  } catch {
    /* not an image sharp can read */
  }
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
const body = Object.entries(sizes)
  .map(([src, [w, h]]) => `  ${JSON.stringify(src)}: [${w}, ${h}],`)
  .join('\n');
fs.writeFileSync(
  OUT,
  '// Generated by scripts/build-image-sizes.mjs (npm run build). Do not edit by hand.\n' +
    `export const HERO_IMAGE_SIZES: Record<string, [number, number]> = {\n${body}\n};\n`
);
console.log(`Wrote ${Object.keys(sizes).length} hero image sizes to ${path.relative(ROOT, OUT)}`);
